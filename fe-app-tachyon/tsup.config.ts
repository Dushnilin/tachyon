import { defineConfig } from 'tsup';
import fs from 'fs';
import path from 'path';

export default defineConfig({
    entry: ['src/main.ts'],
    format: ['esm'], // пусть tsup генерит export {...}
    outDir: '../luci-app-tachyon/htdocs/luci-static/resources/view/tachyon',
    outExtension: () => ({ js: '.js' }),
    dts: false,
    clean: false,
    sourcemap: false,
    banner: {
        js: `// This file is autogenerated, please don't change manually\n"use strict";`,
    },
    esbuildOptions(options) {
        options.legalComments = 'none';
        options.charset = 'utf8';
        options.minifyWhitespace = true;
        options.minifyIdentifiers = true;
    },
    onSuccess: () => {
        const outDir =
            '../luci-app-tachyon/htdocs/luci-static/resources/view/tachyon';
        const file = path.join(outDir, 'main.js');
        let code = fs.readFileSync(file, 'utf8');

        const originalCode = code;
        code = code.replace(
            /("require [^"]+";)/g,
            '$1\n'
        );
        code = code.replace(
            /("require rpc";\n)/,
            '$1var TACHYON_LUCI_APP_VERSION = "__COMPILED_VERSION_VARIABLE__";\n'
        );
        code = code.replace(
            /export\s*\{([\s\S]*?)\}\s*;?\s*$/,
            (match, group) => {
                const mapped = group
                    .split(',')
                    .map((part: string) => part.trim())
                    .filter(Boolean)
                    .map((part: string) => {
                        const m = part.match(/^([\w$]+)\s+as\s+([\w$]+)$/);
                        return m ? `${m[2]}:${m[1]}` : part;
                    })
                    .join(',');
                return `return baseclass.extend({${mapped}});`;
            }
        );

        if (code === originalCode) {
            throw new Error("Failed to patch LuCI build: 'export { ... }' block not found in main.js!");
        }

        fs.writeFileSync(file, code, 'utf8');
        console.log(`✅ Patched LuCI build: ${file}`);
    },
});
