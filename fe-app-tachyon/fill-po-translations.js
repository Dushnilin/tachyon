function escapePoString(str) {
    return str.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

async function run() {
  const poPaths = [
    'locales/tachyon.ru.po',
    '../luci-app-tachyon/po/ru/tachyon.po'
  ];

  for (const p of poPaths) {
    let content = await fs.readFile(p, 'utf8');
    for (const [key, val] of Object.entries(dictionary)) {
      const escapedKey = escapePoString(key);
      const escapedVal = escapePoString(val);
      const searchTarget = `msgid "${escapedKey}"\nmsgstr ""`;
      const searchTargetCRLF = `msgid "${escapedKey}"\r\nmsgstr ""`;
      const replaceWith = `msgid "${escapedKey}"\nmsgstr "${escapedVal}"`;

      if (content.includes(`msgid "${escapedKey}"`)) {
        content = content.replace(searchTarget, replaceWith);
        content = content.replace(searchTargetCRLF, replaceWith);
      } else {
        content += `\nmsgid "${escapedKey}"\nmsgstr "${escapedVal}"\n`;
      }
    }
    await fs.writeFile(p, content, 'utf8');
    console.log(`Updated ${p}`);
  }
}

run().catch(console.error);
